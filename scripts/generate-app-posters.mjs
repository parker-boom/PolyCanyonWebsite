import sharp from 'sharp';
import { chromium } from 'playwright';
import { writeFile, readFile } from 'node:fs/promises';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const previews = {};
try {
  const page = await browser.newPage();
  for (const name of ['explore', 'learn', 'tour']) {
    const bytes = await readFile(`public/media/app-v6/${name}.mp4`);
    const png = await page.evaluate(async (base64) => {
      const binary = atob(base64);
      const data = Uint8Array.from(binary, (c) => c.charCodeAt(0));
      const url = URL.createObjectURL(new Blob([data], { type: 'video/mp4' }));
      const video = document.createElement('video');
      video.muted = true;
      video.preload = 'auto';
      try {
        await new Promise((resolve, reject) => {
          video.onloadeddata = resolve;
          video.onerror = () =>
            reject(new Error('Cannot decode preview recording'));
          video.src = url;
        });
        const canvas = document.createElement('canvas');
        canvas.width = video.videoWidth;
        canvas.height = video.videoHeight;
        canvas.getContext('2d').drawImage(video, 0, 0);
        return canvas.toDataURL('image/png').split(',')[1];
      } finally {
        video.removeAttribute('src');
        video.load();
        URL.revokeObjectURL(url);
      }
    }, bytes.toString('base64'));
    const source = Buffer.from(png, 'base64');
    await sharp(source)
      .resize({ width: 480 })
      .webp({ quality: 84 })
      .toFile(`public/media/app-v6/${name}-poster.webp`);
    const tiny = await sharp(source)
      .resize({ width: 24 })
      .webp({ quality: 45 })
      .toBuffer();
    previews[name] = 'data:image/webp;base64,' + tiny.toString('base64');
  }
} finally {
  await browser.close();
}
await writeFile(
  'src/downloads/preview-placeholders.js',
  '// Generated by scripts/generate-app-posters.mjs.\nexport default ' +
    JSON.stringify(previews, null, 2) +
    ';\n'
);
console.log('Prepared opening-frame posters and inline placeholders.');
